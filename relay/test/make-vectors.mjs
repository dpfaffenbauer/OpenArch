export function swiftSource(vectors) {
  const lines = [
    "// Generated by relay/test/make-vectors.mjs (node relay/test/make-vectors.mjs);",
    "// do not edit. The JavaScript side (website/s/share-core.js) made these with",
    "// fixed keys and nonces, so that the Swift side is tested against it.",
    "",
    "enum Vectors {",
  ];
  for (const [name, value] of Object.entries(vectors)) {
    lines.push(`    /// ${DOCS[name]}`);
    lines.push(typeof value === "number" ? `    static let ${name} = ${value}` : `    static let ${name} = #"${value}"#`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(SWIFT_FILE, swiftSource(await makeVectors()));
  console.log(`wrote ${SWIFT_FILE}`);
}
